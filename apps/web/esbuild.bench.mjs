// Benchmark bundler for `tools/bench/main.ts` → `out/bench/bench.mjs`.
//
// Same pattern as the screenshot runner — esbuild + external playwright.

import { mkdirSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

import esbuild from 'esbuild';

const root = path.dirname(fileURLToPath(import.meta.url));
const watch = process.argv.includes('--watch');

/** @type {import('esbuild').BuildOptions} */
const options = {
  entryPoints: [path.join(root, 'tools/bench/main.ts')],
  outfile: path.join(root, 'out/bench/bench.mjs'),
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node22',
  sourcemap: true,
  logLevel: 'info',
  external: ['playwright', 'ws'],
  banner: {
    js: [
      '// generated by esbuild.bench.mjs — the wing web benchmark runner. Do not edit.',
      "import { createRequire as __wingCreateRequire } from 'node:module';",
      'const require = __wingCreateRequire(import.meta.url);',
    ].join('\n'),
  },
};

mkdirSync(path.join(root, 'out/bench'), { recursive: true });

if (watch) {
  const context = await esbuild.context(options);
  await context.watch();
  process.stdout.write('[esbuild] watching tools/bench/main.ts → out/bench/bench.mjs\n');
} else {
  await esbuild.build(options);
  process.stdout.write('[esbuild] built out/bench/bench.mjs\n');
}
