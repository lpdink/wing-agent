/**
 * The decoder table doubles as the runtime registry.
 *
 * `Record<KnownEventType, …>` is deliberate: adding a variant to
 * {@link KnownWingEvent} without adding a decoder is a compile error, and
 * {@link KNOWN_EVENT_TYPES} is derived from the same object, so the runtime
 * registry can never drift from the union.
 */
const DECODERS: Record<KnownEventType, EventDecoder<KnownWingEvent>> = {
  error: decodeError,
  delivered: decodeDelivered,
  notice: decodeNotice,
  text: decodeText,
  reasoning: decodeReasoning,
  tool_call: decodeToolCall,
  tool_call_stream: decodeToolCallStream,
  tool_call_result: decodeToolCallResult,
  llm_call_metrics: decodeLlmCallMetrics,
  ask: decodeAsk,
  done: decodeDone,
  turn_started: decodeTurnStarted,
  user_message_accepted: decodeUserMessageAccepted,
  diff_content: decodeDiffContent,
  assistant_turn: decodeAssistantTurn,
  tool_result_turn: decodeToolResultTurn,
  turn_result: decodeTurnResult,
  sync_session: decodeSyncSession,
  session_init: decodeSessionInit,
  interrupted: decodeInterrupted,
  compact_done: decodeCompactDone,
  session_state_changed: decodeSessionStateChanged,
  context_stats: decodeContextStats,
  branch_targets: decodeBranchTargets,
};

/** Every `type` this build understands (compare with Python's `EVENT_TYPES`). */
export const KNOWN_EVENT_TYPES: ReadonlySet<string> = new Set(Object.keys(DECODERS));

/**
 * Type guard on the *declared* type: this build knows that `type` string.
 *
 * Note the difference from {@link isKnownEvent}: a known type whose payload
 * failed validation is still "a known type" here (the frame said `text`), but it
 * decoded into the fallback variant.
 */
export function isKnownEventType(type: string): type is KnownEventType {
  return KNOWN_EVENT_TYPES.has(type);
}

/** Type guard: the event decoded into a typed model (not the fallback variant). */
export function isKnownEvent(event: WingEvent): event is KnownWingEvent {
  return !('raw' in event);
}

/**
 * Decode one payload into an event. **Never throws.**
 *
 * Unknown types and payloads that fail validation both come back as an
 * {@link UnknownWingEvent} carrying the raw payload.
 */
export function decodeWingEvent(payload: unknown): WingEvent {
  if (!isJsonObject(payload)) {
    return { type: '', session_id: null, raw: {} };
  }
  const type = payload['type'];
  if (typeof type !== 'string' || !isKnownEventType(type)) {
    return {
      type: typeof type === 'string' ? type : '',
      session_id: optString(payload, 'session_id'),
      raw: payload,
    };
  }
  const decoder = DECODERS[type];
  try {
    return decoder(payload, readMeta(payload));
  } catch (cause) {
    if (!(cause instanceof ProtocolDecodeError)) {
      throw cause;
    }
    return { type, session_id: optString(payload, 'session_id'), raw: payload };
  }
}

// ============================================================
// Local helpers
// ============================================================

function requireObject(payload: JsonObject, key: string): JsonObject {
  const value = payload[key];
  if (!isJsonObject(value)) {
    throw new ProtocolDecodeError(`field "${key}" must be an object`);
  }
  return value;
}

/** Nullable boolean (`SessionStateChangedEvent.thinking` / `.yolo`). */
function optionalBoolean(payload: JsonObject, key: string): boolean | null {
  const value = payload[key];
  if (value === undefined || value === null) {
    return null;
  }
  return reqBoolean(payload, key);
}

/** `uncommitted` is a single message projection or `null`. */
function decodeSingleMessage(payload: JsonObject, key: string): SessionMessage | null {
  const value = payload[key];
  if (value === undefined || value === null) {
    return null;
  }
  const decoded = decodeSessionMessages([value]);
  return decoded[0] ?? null;
}
