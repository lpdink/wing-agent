/**
 * WingEvent mirror — the discriminated union of every event the gateway can push.
 *
 * Source of truth (Python):
 *   - `wing/event/base.py`      — WingEvent base, `error` / `notice` / `delivered`
 *   - `wing/event/react.py`     — react-loop events
 *   - `wing/event/state_change.py`
 *   - `wing/event/query_response.py`
 *   - the registry `EVENT_TYPES` in `wing/event/__init__.py`
 *
 * Wire rules the decoders rely on (`wire_dump`):
 *   - `target` / `parent_uuid` / `unzip_last_uuid` / `role` are stripped before
 *     sending; JSON `null` fields are stripped too, so "absent" always means
 *     "null" and the mirror normalises back to `| null` (never `undefined`).
 *   - `created_at` / `request_id` always exist (the backend generates them);
 *     they are read with an empty-string fallback so an old/hand-made payload
 *     still decodes (same rule as `WingEvent::from_history_value`).
 *
 * Decoding policy (the split matters — it is what keeps replay robust):
 *   - **Scalars are strict**: a required field that is missing or of the wrong
 *     JSON type makes the whole payload an {@link UnknownWingEvent}, never a
 *     typed event with holes in it.
 *   - **Collections of records are tolerant**: elements that do not decode are
 *     skipped (`sync_session` history / replay nodes, `ask.questions`,
 *     `content_blocks`, `branch_targets.targets`), mirroring the backend's own
 *     "skip nodes we do not understand" replay semantics.
 *   - **Unknown `type` is forward compatible**: it arrives as an
 *     {@link UnknownWingEvent} with the raw payload, never dropped.
 */

