/** `error` — the failure event; replaces scattered status codes. */
export interface ErrorEvent extends EventMeta {
  readonly type: 'error';
  readonly status_code: number;
  readonly message: string;
  readonly error_code: string | null;
  readonly detail: string | null;
}

/** `delivered` — transport ack: the request reached the backend. */
export interface DeliveredEvent extends EventMeta {
  readonly type: 'delivered';
}

/** `notice` level (unknown values degrade to `info`, like the Rust mirror). */
export const NOTICE_LEVELS = ['info', 'warning', 'error'] as const;
export type NoticeLevel = (typeof NOTICE_LEVELS)[number];

/**
 * `notice` — a one-shot hint that is **not** an error and **not** end-of-turn
 * (e.g. "LLM call failed, retrying in N s"). A frontend must not finish the turn
 * on it. Broadcast-only: never replayed from history.
 */
export interface NoticeEvent extends EventMeta {
  readonly type: 'notice';
  readonly level: NoticeLevel;
  readonly message: string;
  readonly attempt: number | null;
  readonly max_attempts: number | null;
  readonly retry_in_s: number | null;
}

/** `text` — assistant text delta. */
export interface TextEvent extends EventMeta {
  readonly type: 'text';
  readonly content: string;
}

/** `reasoning` — thinking / reasoning delta. */
export interface ReasoningEvent extends EventMeta {
  readonly type: 'reasoning';
  readonly content: string;
}

/** `tool_call` — a tool call starts executing (authoritative parsed args). */
export interface ToolCallEvent extends EventMeta {
  readonly type: 'tool_call';
  readonly tool_name: string;
  readonly tool_args: JsonObject;
  readonly tool_call_id: string;
}

/**
 * `tool_call_stream` — raw args text fragment while the LLM is still generating.
 *
 * Fragments accumulate into the full args text; the backend never parses partial
 * JSON, so neither does `src/core` — that belongs to the host's renderers.
 */
export interface ToolCallStreamEvent extends EventMeta {
  readonly type: 'tool_call_stream';
  readonly tool_call_id: string;
  readonly tool_name: string;
  readonly args_fragment: string;
  readonly is_final: boolean;
}

/** `tool_call_result` — a tool finished (live only; `persist = false`). */
export interface ToolCallResultEvent extends EventMeta {
  readonly type: 'tool_call_result';
  readonly tool_name: string;
  readonly tool_args: JsonObject;
  readonly tool_call_id: string;
  readonly tool_result: string;
  readonly tool_success: boolean;
  readonly model: string;
}

/** `llm_call_metrics` — usage / latency of one LLM call. */
export interface LlmCallMetricsEvent extends EventMeta {
  readonly type: 'llm_call_metrics';
  readonly model: string;
  readonly prompt_tokens: number;
  readonly completion_tokens: number;
  readonly cached_tokens: number;
  readonly first_chunk_rt_ms: number;
  readonly tokens_per_sec: number;
  /** Protocol-native stop reason (`end_turn` / `max_tokens` / `tool_use` / `stop` / `length`). */
  readonly stop_reason: string | null;
}

/**
 * `ask` — the agent needs user input.
 *
 * Two shapes coexist: the multi-question `AskUserQuestion` tool fills
 * `questions`, the legacy Bash-confirmation path fills `question` + `choices`.
 * `tool_call_id` addresses the reply (`ClientRequest.tool_call_id`).
 */
export interface AskEvent extends EventMeta {
  readonly type: 'ask';
  readonly tool_call_id: string;
  readonly questions: readonly AskQuestion[];
  readonly question: string;
  readonly choices: readonly string[];
  readonly required: boolean;
}

/** `done` — the agent loop finished. */
export interface DoneEvent extends EventMeta {
  readonly type: 'done';
}

/** `turn_started` — the agent started processing a user message. */
export interface TurnStartedEvent extends EventMeta {
  readonly type: 'turn_started';
}

/**
 * `user_message_accepted` — the message was injected into the model context.
 *
 * `origin_request_id` is the `ClientRequest.request_id` the client submitted, so
 * the host can move its local echo from "queued" to "sent".
 */
export interface UserMessageAcceptedEvent extends EventMeta {
  readonly type: 'user_message_accepted';
  readonly content: string;
  readonly origin_request_id: string;
}

/** `diff_content` — diff payload for Write / Edit / BetterEdit. */
export interface DiffContentEvent extends EventMeta {
  readonly type: 'diff_content';
  readonly path: string;
  /** `null` means "new file" (whole file is green). */
  readonly old_text: string | null;
  readonly new_text: string;
  /** 1-based absolute line number of the window's first line in the old revision. */
  readonly old_start_line: number;
  readonly new_start_line: number;
  readonly tool_call_id: string;
}

/** `assistant_turn` — turn-level complete assistant message (stdio consumers). */
export interface AssistantTurnEvent extends EventMeta {
  readonly type: 'assistant_turn';
  readonly content_blocks: readonly JsonObject[];
  readonly model: string;
  readonly stop_reason: string | null;
  readonly usage: JsonObject | null;
}

/** `tool_result_turn` — turn-level tool result (stdio consumers). */
export interface ToolResultTurnEvent extends EventMeta {
  readonly type: 'tool_result_turn';
  readonly tool_use_id: string;
  readonly tool_name: string;
  readonly content: string;
  readonly is_error: boolean;
}

/** `turn_result` — final result of a whole agent loop. */
export interface TurnResultEvent extends EventMeta {
  readonly type: 'turn_result';
  readonly subtype: string;
  readonly is_error: boolean;
  readonly result: string | null;
  readonly num_turns: number;
  readonly duration_ms: number;
  readonly usage: JsonObject | null;
  readonly errors: readonly string[];
}

/**
 * `sync_session` — the full replay payload pushed on subscribe / fork / rewind.
 *
 * Consumers MUST assemble in the documented order
 * `messages → uncommitted → uncommitted_tools → events` and then continue with
 * the live stream. `events` are decoded into {@link WingEvent}s on purpose: the
 * replay facts (diff / ask / interrupted / error / compact_done) therefore take
 * the *same* reduction path as live events in the host.
 */
export interface SyncSessionEvent extends EventMeta {
  readonly type: 'sync_session';
  readonly session_id: string;
  readonly messages: readonly SessionMessage[];
  readonly uncommitted: SessionMessage | null;
  readonly uncommitted_tools: readonly UncommittedTool[];
  readonly events: readonly WingEvent[];
  /** Turn start time (UTC ISO) — restore an in-flight turn's elapsed time. */
  readonly turn_started_at: string | null;
  readonly agent: AgentInfo | null;
  readonly name: string | null;
  readonly draft: string | null;
}

/** `session_init` — authoritative session state after subscribe (stdio mode). */
export interface SessionInitEvent extends EventMeta {
  readonly type: 'session_init';
  readonly tools: readonly string[];
  readonly model: string;
  readonly permission_mode: string;
  readonly cwd: string;
}

/** `interrupted` — the user aborted the running turn. */
export interface InterruptedEvent extends EventMeta {
  readonly type: 'interrupted';
}

/** `compact_done` — manual compaction finished. */
export interface CompactDoneEvent extends EventMeta {
  readonly type: 'compact_done';
  readonly original_tokens: number;
  readonly compressed_tokens: number;
  readonly model: string;
}

/** `session_state_changed` — one event for model / thinking / effort / yolo / title / agent. */
export interface SessionStateChangedEvent extends EventMeta {
  readonly type: 'session_state_changed';
  readonly model: string | null;
  readonly thinking: boolean | null;
  readonly reasoning_effort: string | null;
  readonly yolo: boolean | null;
  readonly title: string | null;
  readonly agent: string | null;
}

/** `context_stats` — context window usage, emitted after every LLM turn. */
export interface ContextStatsEvent extends EventMeta {
  readonly type: 'context_stats';
  readonly message_count: number;
  readonly total_tokens: number;
  readonly context_window_tokens: number;
  readonly system_prompt_parts: readonly string[];
}

/** `branch_targets` — rewind / fork candidates. */
export interface BranchTargetsEvent extends EventMeta {
  readonly type: 'branch_targets';
  readonly targets: readonly BranchTarget[];
}

/** Every event type this client knows how to decode. */
export type KnownWingEvent =
  | ErrorEvent
  | DeliveredEvent
  | NoticeEvent
  | TextEvent
  | ReasoningEvent
  | ToolCallEvent
  | ToolCallStreamEvent
  | ToolCallResultEvent
  | LlmCallMetricsEvent
  | AskEvent
  | DoneEvent
  | TurnStartedEvent
  | UserMessageAcceptedEvent
  | DiffContentEvent
  | AssistantTurnEvent
  | ToolResultTurnEvent
  | TurnResultEvent
  | SyncSessionEvent
  | SessionInitEvent
  | InterruptedEvent
  | CompactDoneEvent
  | SessionStateChangedEvent
  | ContextStatsEvent
  | BranchTargetsEvent;

/** The discriminated tag of every known event. */
export type KnownEventType = KnownWingEvent['type'];

/**
 * An event this client cannot represent as a typed model.
 *
 * Either the `type` is unknown (forward compatibility: a newer gateway) or a
 * *known* type arrived with a payload that failed validation. Both are surfaced
 * the same way — with the raw payload — so the host can log / ignore them, but it
 * can never receive a half-filled typed event.
 *
 * The `raw` field doubles as the runtime discriminant: no known event has it, so
 * {@link isKnownEvent} can narrow the union without inspecting the payload.
 */
export interface UnknownWingEvent {
  /** Whatever the frame declared (empty string when the payload had no `type`). */
  readonly type: string;
  /** Routing convenience: `session_id` extracted from the payload when present. */
  readonly session_id: string | null;
  /** The untouched payload. */
  readonly raw: JsonObject;
}

/** Anything the gateway can push over the event stream. */
export type WingEvent = KnownWingEvent | UnknownWingEvent;

// ============================================================
// Decoders
// ============================================================

type EventDecoder<T extends KnownWingEvent> = (payload: JsonObject, meta: EventMeta) => T;

function readMeta(payload: JsonObject): EventMeta {
  return {
    created_at: stringOr(payload, 'created_at', ''),
    request_id: stringOr(payload, 'request_id', ''),
    session_id: optString(payload, 'session_id'),
    uuid: optString(payload, 'uuid'),
  };
}

/** Decode the replay facts of `sync_session.events` with the live-event decoder. */
function decodeEventList(object: JsonObject, key: string): WingEvent[] {
  return readJsonArray(object, key)
    .filter(isJsonObject)
    .map((value) => decodeWingEvent(value));
}

