/**
 * The smoke's real gateway: locate the binary, boot an **isolated** instance,
 * wait for health, shut it down.
 *
 * Isolation is the hard requirement (the user's own gateway runs on 32523 against
 * `~/.wing`):
 *
 * - a temp `WING_HOME` + `WING_SESSIONS_PATH` under `os.tmpdir()`, injected into
 *   the child's environment — the smoke never reads or writes `~/.wing`;
 * - the port is an OS-assigned free one (`listen(0)` + close): the smoke refuses
 *   to run on the user's port even by accident (`assertIsolated` below);
 * - `autoStart: false` on the host side, so the launcher only ever *probes*;
 * - shutdown is `/api/shutdown` → SIGTERM → SIGKILL, always run in a `finally`.
 */

import { spawn } from 'node:child_process';
import type { ChildProcess } from 'node:child_process';
import { existsSync, mkdirSync, openSync, closeSync, readFileSync, writeFileSync } from 'node:fs';
import { createServer } from 'node:net';
import os from 'node:os';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

import type { FakeProvider } from './fake-provider';

/** The user's live gateway port — never touch it. */
export const FORBIDDEN_PORT = 32_523;

export interface GatewayBinary {
  readonly path: string;
  /** Where it came from (for the report). */
  readonly source: string;
}

const here = path.dirname(fileURLToPath(import.meta.url));
/** `<repo>/extensions/vscode/tools/smoke` → `<repo>`. */
export const repoRoot = path.resolve(here, '..', '..', '..', '..');

/**
 * Resolve `wing-gateway`.
 *
 * Order: `$WING_GATEWAY_BIN` → the checkout's `.venv` → `PATH`. `null` means
 * "skip the smoke" (the caller turns that into exit code 3 with a readable
 * message) — never a hard failure, because not having the gateway installed is a
 * perfectly normal state for a front-end-only checkout.
 */
export function findGatewayBinary(env: NodeJS.ProcessEnv = process.env): GatewayBinary | null {
  const override = env['WING_GATEWAY_BIN'];
  if (override !== undefined && override !== '') {
    if (existsSync(override)) {
      return { path: override, source: '$WING_GATEWAY_BIN' };
    }
    throw new Error(`$WING_GATEWAY_BIN points at a missing file: ${override}`);
  }
  const candidates = [
    path.join(repoRoot, '.venv', 'bin', 'wing-gateway'),
    path.join(repoRoot, '.venv', 'Scripts', 'wing-gateway.exe'),
  ];
  for (const candidate of candidates) {
    if (existsSync(candidate)) {
      return { path: candidate, source: 'repository .venv' };
    }
  }
  for (const directory of (env['PATH'] ?? '').split(path.delimiter)) {
    if (directory === '') {
      continue;
    }
    const candidate = path.join(directory, 'wing-gateway');
    if (existsSync(candidate)) {
      return { path: candidate, source: 'PATH' };
    }
  }
  return null;
}

/** Pick a free port (bind(0), read, release). Small race window; acceptable. */
export async function freePort(): Promise<number> {
  const server = createServer();
  await new Promise<void>((resolve, reject) => {
    server.once('error', reject);
    server.listen(0, '127.0.0.1', resolve);
  });
  const address = server.address();
  const port = typeof address === 'object' && address !== null ? address.port : 0;
  await new Promise<void>((resolve) => {
    server.close(() => {
      resolve();
    });
  });
  if (port === FORBIDDEN_PORT) {
    throw new Error(`refusing to use the user's gateway port ${FORBIDDEN_PORT}`);
  }
  return port;
}

