export interface SmokeGatewayOptions {
  readonly binary: GatewayBinary;
  readonly provider: FakeProvider;
  readonly model: string;
  readonly root: string;
  readonly logFile: string;
}

export class SmokeGateway {
  readonly root: string;
  readonly wingHome: string;
  readonly sessionsPath: string;
  readonly workspace: string;
  readonly logFile: string;
  readonly model: string;

  private process: ChildProcess | null = null;
  private logFd: number | null = null;
  private readonly binary: GatewayBinary;
  private readonly provider: FakeProvider;
  private portValue = 0;

  constructor(options: SmokeGatewayOptions) {
    this.binary = options.binary;
    this.provider = options.provider;
    this.model = options.model;
    this.root = options.root;
    this.wingHome = path.join(options.root, 'wing_home');
    this.sessionsPath = path.join(options.root, 'sessions');
    this.workspace = path.join(options.root, 'workspace');
    this.logFile = options.logFile;
  }

  get port(): number {
    return this.portValue;
  }

  get baseUrl(): string {
    return `http://127.0.0.1:${this.portValue}`;
  }

  async start(): Promise<void> {
    mkdirSync(path.join(this.wingHome, 'core'), { recursive: true });
    mkdirSync(this.sessionsPath, { recursive: true });
    mkdirSync(this.workspace, { recursive: true });
    const forced = Number(process.env['WING_SMOKE_GATEWAY_PORT'] ?? Number.NaN);
    this.portValue = Number.isInteger(forced) && forced > 0 ? forced : await freePort();
    assertIsolated(this.portValue);
    writeFileSync(
      path.join(this.wingHome, 'core', 'config.yaml'),
      renderConfig({ providerBaseUrl: this.provider.baseUrl, port: this.portValue, model: this.model }),
      'utf8',
    );

    this.logFd = openSync(this.logFile, 'a');
    const child = spawn(this.binary.path, ['-p', String(this.portValue)], {
      cwd: this.root,
      env: {
        ...process.env,
        WING_HOME: this.wingHome,
        WING_SESSIONS_PATH: this.sessionsPath,
        PYTHONUNBUFFERED: '1',
      },
      stdio: ['ignore', this.logFd, this.logFd],
    });
    this.process = child;

    await this.waitForHealth(30_000);
  }

  private async waitForHealth(timeoutMs: number): Promise<void> {
    const deadline = Date.now() + timeoutMs;
    for (;;) {
      const child = this.process;
      if (child === null) {
        throw new Error('gateway process is gone');
      }
      if (child.exitCode !== null || child.signalCode !== null) {
        throw new Error(
          `wing-gateway exited before becoming healthy (code=${child.exitCode}, signal=${child.signalCode})\n` +
            this.logTail(),
        );
      }
      try {
        const response = await fetch(`${this.baseUrl}/api/health`);
        if (response.ok) {
          const body = (await response.json()) as { service?: unknown };
          if (body.service !== 'wing-gateway') {
            throw new Error(`health answered but is not a wing gateway: ${JSON.stringify(body)}`);
          }
          return;
        }
      } catch {
        // not listening yet
      }
      if (Date.now() >= deadline) {
        throw new Error(`health check timed out after ${timeoutMs} ms\n${this.logTail()}`);
      }
      await new Promise<void>((resolve) => {
        setTimeout(resolve, 50);
      });
    }
  }

  logTail(lines = 40): string {
    try {
      const text = readFileSync(this.logFile, 'utf8');
      return `--- gateway.log tail (${this.logFile}) ---\n${text.split('\n').slice(-lines).join('\n')}`;
    } catch {
      return `--- gateway.log (${this.logFile}) unavailable ---`;
    }
  }

  /** `/api/shutdown` → wait → SIGTERM → SIGKILL. Idempotent, never throws. */
  async stop(): Promise<void> {
    const child = this.process;
    this.process = null;
    if (child !== null && child.exitCode === null) {
      try {
        await fetch(`${this.baseUrl}/api/shutdown`, { method: 'POST', body: '{}' });
      } catch {
        // already gone
      }
      const exited = await waitForExit(child, 5_000);
      if (!exited) {
        child.kill('SIGTERM');
        const terminated = await waitForExit(child, 5_000);
        if (!terminated) {
          child.kill('SIGKILL');
          await waitForExit(child, 5_000);
        }
      }
    }
    if (this.logFd !== null) {
      closeSync(this.logFd);
      this.logFd = null;
    }
  }
}

/** Belt and braces: the smoke must never talk to the user's live gateway. */
export function assertIsolated(port: number): void {
  if (port === FORBIDDEN_PORT) {
    throw new Error(
      `the smoke refuses to use port ${FORBIDDEN_PORT}: that is the user's live gateway. ` +
        'Isolate the run (temp WING_HOME + an OS-assigned port).',
    );
  }
}

function waitForExit(child: ChildProcess, timeoutMs: number): Promise<boolean> {
  if (child.exitCode !== null || child.signalCode !== null) {
    return Promise.resolve(true);
  }
  return new Promise<boolean>((resolve) => {
    const timer = setTimeout(() => {
      resolve(false);
    }, timeoutMs);
    child.once('exit', () => {
      clearTimeout(timer);
      resolve(true);
    });
  });
}

/** Where the smoke keeps its scratch state (overridable for debugging). */
export function smokeRoot(): string {
  const override = process.env['WING_SMOKE_ROOT'];
  const root =
    override !== undefined && override !== '' ? override : path.join(os.tmpdir(), 'wing-vscode-smoke');
  mkdirSync(root, { recursive: true });
  return root;
}
