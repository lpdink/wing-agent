def test_read_log_tail(tmp_path: Path) -> None:
    path = tmp_path / "gateway.log"
    path.write_text("\n".join(f"line {i}" for i in range(100)), encoding="utf-8")
    tail = read_log_tail(path, max_lines=5)
    assert tail.splitlines() == [f"line {i}" for i in range(95, 100)]
    assert read_log_tail(tmp_path / "missing.log").startswith("(cannot read")
    assert read_log_tail(None) == "(no log file)"

    truncated = read_log_tail(path, max_lines=100, max_chars=20)
    assert truncated.startswith("…")
    assert len(truncated) == 21

    section = log_section(path, title="gateway.log tail")
    assert section.startswith(f"--- gateway.log tail ({path}) ---")


