@pytest.mark.asyncio
async def test_wait_for_health_reports_dead_process(tmp_path: Path) -> None:
    class DeadProcess:
        returncode = 3

        def poll(self) -> int:
            return 3

    log = tmp_path / "gateway.log"
    log.write_text("address already in use\n", encoding="utf-8")
    dead_process = cast(Any, DeadProcess())
    with pytest.raises(ProbeEnvError) as excinfo:
        await wait_for_health(
            "http://127.0.0.1:1/api/health",
            timeout=5.0,
            interval=0.01,
            process=dead_process,
            log_path=log,
        )
    message = str(excinfo.value)
    assert "exited with code 3" in message
    assert "address already in use" in message


