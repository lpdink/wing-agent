async def _start_health_app(status: int) -> tuple[web.AppRunner, int]:
    app = web.Application()

    async def handler(request: web.Request) -> web.Response:
        return web.Response(status=status, text="ok" if status == 200 else "nope")

    app.router.add_get("/api/health", handler)
    runner = web.AppRunner(app, access_log=None)
    await runner.setup()
    sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    sock.bind(("127.0.0.1", 0))
    sock.listen(8)
    sock.setblocking(False)
    port = int(sock.getsockname()[1])
    await web.SockSite(runner, sock).start()
    return runner, port


@pytest.mark.asyncio
async def test_wait_for_health_returns_when_ready() -> None:
    runner, port = await _start_health_app(200)
    try:
        await wait_for_health(
            f"http://127.0.0.1:{port}/api/health", timeout=5.0, interval=0.01
        )
    finally:
        await runner.cleanup()


@pytest.mark.asyncio
async def test_wait_for_health_times_out_with_log_tail(tmp_path: Path) -> None:
    runner, port = await _start_health_app(500)
    log = tmp_path / "gateway.log"
    log.write_text("ERROR: something went wrong\n", encoding="utf-8")
    try:
        with pytest.raises(ProbeEnvError) as excinfo:
            await wait_for_health(
                f"http://127.0.0.1:{port}/api/health",
                timeout=0.3,
                interval=0.05,
                log_path=log,
            )
    finally:
        await runner.cleanup()
    message = str(excinfo.value)
    assert "health check timed out after 0.3s" in message
    assert "last status: 500" in message
    assert "ERROR: something went wrong" in message


@pytest.mark.asyncio
async def test_wait_for_health_reports_dead_process(tmp_path: Path) -> None:
    class DeadProcess:
        returncode = 3

        def poll(self) -> int:
            return 3

    log = tmp_path / "gateway.log"
    log.write_text("address already in use\n", encoding="utf-8")
    dead_process = cast(Any, DeadProcess())
    with pytest.raises(ProbeEnvError) as excinfo:
        await wait_for_health(
            "http://127.0.0.1:1/api/health",
            timeout=5.0,
            interval=0.01,
            process=dead_process,
            log_path=log,
        )
    message = str(excinfo.value)
    assert "exited with code 3" in message
    assert "address already in use" in message


@pytest.mark.asyncio
async def test_wait_for_health_reports_unreachable_url(tmp_path: Path) -> None:
    # 关闭的端口：连接被拒 → 报 no response
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as probe:
        probe.bind(("127.0.0.1", 0))
        port = int(probe.getsockname()[1])
    with pytest.raises(ProbeEnvError, match="no response"):
        await wait_for_health(
            f"http://127.0.0.1:{port}/api/health", timeout=0.2, interval=0.05
        )
