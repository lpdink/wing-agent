@pytest.mark.asyncio
async def test_restart_gateway_without_running_process_starts_one(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """未起进程时重启 = 起一个新的（不重复起第二个）。"""
    env = ProbeEnv(tmp_path)
