def test_render_config_points_provider_at_fake() -> None:
    text = render_config_yaml(
        provider_base_url="http://127.0.0.1:45123/v1", gateway_port=45124
    )
    config = yaml.safe_load(text)

    provider = config["providers"][0]
    assert provider["protocol"] == "openai"
    assert provider["base_url"] == "http://127.0.0.1:45123/v1"
    assert provider["api_key"] == "probe-key"
    # 重试 / 退避不进首批：一次请求 = 一次剧本消费
    assert provider["max_retries"] == 0

    agent = config["agents"][0]
    assert agent["name"] == "default"
    assert agent["default"] is True
    assert agent["model"] == DEFAULT_PROBE_MODEL
    assert agent["provider"] == provider["name"]
    # system prompt 非空：system 段要真的进请求（"system + 摘要/前缀"断言的前提）
    assert agent["system_prompt"] == DEFAULT_SYSTEM_PROMPT
    assert agent["system_prompt"].strip()
    assert tuple(agent["tools"]) == DEFAULT_AGENT_TOOLS
    assert agent["skills"] == [] and agent["rules"] == []

    assert config["gateway"]["port"] == 45124
    assert config["gateway"]["auth"]["enabled"] is False
    assert config["yolo"] is False
    assert text.startswith("# generated by wing-probe")


